const s2=await st().catch(e=>({err:1}));if(!s2.own)console.log('DBG',code.length,JSON.stringify(await p.evaluate(()=>[localStorage.getItem('fishtankmath.v1'),document.getElementById('codeMsg').textContent])));ok(JSON.stringify([...s2.own].sort())===JSON.stringify([...s.own].sort())&&s2.starsSpent===s.starsSpent&&s2.on.includes('castle')&&s2.on.includes('mint'),'save code restores shop');
